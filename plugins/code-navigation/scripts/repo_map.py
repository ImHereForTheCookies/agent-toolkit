#!/usr/bin/env python3
"""Write a compact symbol index (repo map) of a source tree.

Usage: repo_map.py <root> [--out docs/symbols.md] [--max-bytes N]

One line per source file, sorted by path:

    path: Class(L12), func(L30), Class.method(L40)

Python files are parsed with `ast` (classes, functions, and methods one level
deep). .js/.jsx/.ts/.tsx files use line regexes for unindented declarations.
Output is deterministic (no timestamps), so the file only changes when code
changes. Stdlib only.
"""
import argparse
import ast
import os
import re
import sys

SKIP_DIRS = {".git", ".venv", "venv", "node_modules", "__pycache__", "dist", "build"}
JS_EXTS = {".js", ".jsx", ".ts", ".tsx"}
HEADER = ("# Generated by repo_map.py - do not edit. Regenerate with: "
          "make symbols (python3 <toolkit>/plugins/code-navigation/scripts/repo_map.py . --out docs/symbols.md)")

_EXPORT = r"(?:export\s+(?:default\s+)?)?"
JS_PATTERNS = [
    re.compile(rf"^{_EXPORT}(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)"),
    re.compile(rf"^{_EXPORT}(?:abstract\s+)?class\s+([A-Za-z_$][\w$]*)"),
    re.compile(rf"^{_EXPORT}const\s+([A-Za-z_$][\w$]*)\s*(?::[^=]+)?=\s*(?:async\s+)?"
               r"(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*(?::\s*[^=]+?)?\s*=>"),
]


def python_symbols(source):
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError):
        return []
    out = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append(f"{node.name}(L{node.lineno})")
        elif isinstance(node, ast.ClassDef):
            out.append(f"{node.name}(L{node.lineno})")
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    out.append(f"{node.name}.{sub.name}(L{sub.lineno})")
    return out


def js_symbols(source):
    out = []
    for lineno, line in enumerate(source.splitlines(), 1):
        for pat in JS_PATTERNS:
            m = pat.match(line)
            if m:
                out.append(f"{m.group(1)}(L{lineno})")
                break
    return out


def iter_files(root):
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            ext = os.path.splitext(name)[1]
            if ext == ".py" or ext in JS_EXTS:
                full = os.path.join(dirpath, name)
                found.append((os.path.relpath(full, root).replace(os.sep, "/"), full))
    return sorted(found)


def file_line(rel, full):
    with open(full, encoding="utf-8", errors="replace") as fh:
        source = fh.read()
    symbols = python_symbols(source) if rel.endswith(".py") else js_symbols(source)
    return f"{rel}: {', '.join(symbols)}" if symbols else f"{rel}:"


def build(root, max_bytes=None):
    lines = [file_line(rel, full) for rel, full in iter_files(root)]
    size = lambda s: len(s.encode("utf-8")) + 1  # + newline
    if max_bytes is None or size(HEADER) + sum(map(size, lines)) <= max_bytes:
        return [HEADER] + lines
    # Keep the largest whole-line prefix that leaves room for the marker.
    used, kept = size(HEADER), 0
    for i, line in enumerate(lines):
        marker = f"... truncated ({len(lines) - i - 1} more files)"
        if used + size(line) + size(marker) > max_bytes:
            break
        used += size(line)
        kept = i + 1
    return [HEADER] + lines[:kept] + [f"... truncated ({len(lines) - kept} more files)"]


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write a symbol index of a source tree.")
    ap.add_argument("root", help="directory to scan")
    ap.add_argument("--out", help="write here instead of stdout (parent dirs are created)")
    ap.add_argument("--max-bytes", type=int, help="cap output size; truncates at a whole line with a marker")
    args = ap.parse_args(argv)
    if not os.path.isdir(args.root):
        print(f"repo_map: not a directory: {args.root}", file=sys.stderr)
        return 2
    text = "\n".join(build(args.root, args.max_bytes)) + "\n"
    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
